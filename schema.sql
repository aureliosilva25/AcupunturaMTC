-- MTC Acupuntura Pro: armazenamento por usuário autenticado.
-- Execute no SQL Editor do projeto Supabase. Não habilite acesso público.
create table if not exists public.mtc_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_type text not null check (record_type in ('clientes','anamneses','evolucoes','progressoCursos')),
  record_id text not null,
  payload jsonb not null,
  updated_at timestamptz not null default now(),
  unique (user_id, record_type, record_id)
);
create index if not exists mtc_records_user_type_idx on public.mtc_records(user_id, record_type);
alter table public.mtc_records enable row level security;
drop policy if exists "Usuário acessa somente seus registros" on public.mtc_records;
create policy "Usuário acessa somente seus registros"
  on public.mtc_records for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
revoke all on public.mtc_records from anon;
grant select, insert, update, delete on public.mtc_records to authenticated;
grant usage, select on sequence public.mtc_records_id_seq to authenticated;
